//! Text insertion & clipboard. OWNER: platform agent.

/// Insert `text` at the caret of the frontmost app.
/// macOS: snapshot the general pasteboard (all items/types), write text (flagged transient so clipboard managers
/// ignore it), post Cmd+V via CGEvent, then restore the original pasteboard ~450 ms later (on a background thread)
/// unless the user copied something in the meantime.
///
/// Blocks for roughly 20-60 ms (pasteboard snapshot + key events); call from a blocking-friendly thread,
/// never from inside the hotkey callback.
pub fn insert_text(text: &str) -> anyhow::Result<()> {
    #[cfg(target_os = "macos")]
    {
        mac_impl::insert_text(text)
    }
    #[cfg(not(target_os = "macos"))]
    {
        let _ = text;
        anyhow::bail!("insert_text is not implemented on this OS")
    }
}

/// Replace the current selection with `text` (same mechanism as insert — paste replaces selection).
pub fn replace_selection(text: &str) -> anyhow::Result<()> {
    insert_text(text)
}

/// Put text on the clipboard permanently (user-initiated copy).
pub fn copy_to_clipboard(text: &str) -> anyhow::Result<()> {
    #[cfg(target_os = "macos")]
    {
        mac_impl::copy_to_clipboard(text)
    }
    #[cfg(not(target_os = "macos"))]
    {
        let _ = text;
        anyhow::bail!("copy_to_clipboard is not implemented on this OS")
    }
}

#[cfg(target_os = "macos")]
pub(crate) use mac_impl::{keycode_for_char, restore_snapshot, snapshot_pasteboard};

#[cfg(target_os = "macos")]
mod mac_impl {
    use crate::platform::mac::{is_main_thread, on_main_queue, post_key_press};
    use core_foundation::base::{CFRelease, CFTypeRef, TCFType};
    use core_foundation::data::CFData;
    use core_graphics::event::CGEventFlags;
    use objc2::rc::Retained;
    use objc2::runtime::ProtocolObject;
    use objc2_app_kit::{NSPasteboard, NSPasteboardItem, NSPasteboardWriting};
    use objc2_foundation::{NSArray, NSData, NSString};
    use parking_lot::Mutex;
    use std::ffi::c_void;
    use std::time::{Duration, Instant};

    const RESTORE_DELAY: Duration = Duration::from_millis(450);
    const TYPE_STRING: &str = "public.utf8-plain-text";
    const TYPE_TRANSIENT: &str = "org.nspasteboard.TransientType";
    const TYPE_AUTO_GENERATED: &str = "org.nspasteboard.AutoGeneratedType";
    /// Refuse to snapshot absurdly large individual flavors (would stall the paste).
    const MAX_FLAVOR_BYTES: usize = 64 * 1024 * 1024;

    /// Everything that was on the pasteboard: items -> (type, bytes).
    #[derive(Default)]
    pub(crate) struct PasteboardSnapshot {
        items: Vec<Vec<(String, Vec<u8>)>>,
    }

    struct Pending {
        snapshot: PasteboardSnapshot,
        generation: u64,
        expected_change_count: isize,
    }

    static PENDING: Mutex<Option<Pending>> = Mutex::new(None);
    static GENERATION: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);

    pub(crate) fn snapshot_pasteboard(pb: &NSPasteboard) -> PasteboardSnapshot {
        let mut snap = PasteboardSnapshot::default();
        let Some(items) = pb.pasteboardItems() else {
            return snap;
        };
        for item in items.iter() {
            let mut flavors = Vec::new();
            for t in item.types().iter() {
                if let Some(data) = item.dataForType(&t) {
                    if data.length() <= MAX_FLAVOR_BYTES {
                        flavors.push((t.to_string(), data.to_vec()));
                    } else {
                        log::debug!("pasteboard flavor {t} too large to snapshot, skipped");
                    }
                }
            }
            if !flavors.is_empty() {
                snap.items.push(flavors);
            }
        }
        snap
    }

    pub(crate) fn restore_snapshot(pb: &NSPasteboard, snap: &PasteboardSnapshot) {
        pb.clearContents();
        if snap.items.is_empty() {
            return;
        }
        let mut objects: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = Vec::new();
        for flavors in &snap.items {
            let item = NSPasteboardItem::new();
            for (t, bytes) in flavors {
                item.setData_forType(&NSData::with_bytes(bytes), &NSString::from_str(t));
            }
            objects.push(ProtocolObject::from_retained(item));
        }
        let array = NSArray::from_retained_slice(&objects);
        if !pb.writeObjects(&array) {
            log::warn!("restoring the pasteboard failed");
        }
    }

    fn write_transient_text(pb: &NSPasteboard, text: &str) -> bool {
        pb.clearContents();
        let item = NSPasteboardItem::new();
        let ok = item.setString_forType(&NSString::from_str(text), &NSString::from_str(TYPE_STRING));
        let empty = NSData::new();
        item.setData_forType(&empty, &NSString::from_str(TYPE_TRANSIENT));
        item.setData_forType(&empty, &NSString::from_str(TYPE_AUTO_GENERATED));
        let array = NSArray::from_retained_slice(&[ProtocolObject::<dyn NSPasteboardWriting>::from_retained(item)]);
        ok && pb.writeObjects(&array)
    }

    pub fn insert_text(text: &str) -> anyhow::Result<()> {
        if text.is_empty() {
            return Ok(());
        }
        let pb = NSPasteboard::generalPasteboard();
        let generation;
        let expected;
        {
            let mut pending = PENDING.lock();
            // A previous paste may still be waiting to restore: its snapshot is the real clipboard, not what we wrote.
            let snapshot = match pending.take() {
                Some(p) => p.snapshot,
                None => snapshot_pasteboard(&pb),
            };
            if !write_transient_text(&pb, text) {
                restore_snapshot(&pb, &snapshot);
                anyhow::bail!("could not write the text to the pasteboard");
            }
            expected = pb.changeCount();
            generation = GENERATION.fetch_add(1, std::sync::atomic::Ordering::SeqCst) + 1;
            *pending = Some(Pending { snapshot, generation, expected_change_count: expected });
        }

        let v = keycode_for_char('v');
        if let Err(e) = post_key_press(v, CGEventFlags::CGEventFlagCommand) {
            finish_restore(generation, true);
            return Err(e);
        }

        std::thread::Builder::new()
            .name("hoshiro-pasteboard-restore".into())
            .spawn(move || {
                std::thread::sleep(RESTORE_DELAY);
                finish_restore(generation, false);
            })
            .map_err(|e| anyhow::anyhow!("failed to spawn pasteboard restore thread: {e}"))?;
        Ok(())
    }

    /// Restore the pasteboard if `generation` is still the latest paste. `force` skips the changeCount check.
    fn finish_restore(generation: u64, force: bool) {
        let mut pending = PENDING.lock();
        match pending.as_ref() {
            Some(p) if p.generation == generation => {}
            _ => return, // superseded by a newer paste or a user-initiated copy
        }
        let p = pending.take().expect("checked above");
        let pb = NSPasteboard::generalPasteboard();
        if force || pb.changeCount() == p.expected_change_count {
            restore_snapshot(&pb, &p.snapshot);
        } else {
            log::debug!("pasteboard changed during paste; leaving the user's newer clipboard alone");
        }
    }

    pub fn copy_to_clipboard(text: &str) -> anyhow::Result<()> {
        *PENDING.lock() = None; // never let a delayed restore overwrite an explicit copy
        let pb = NSPasteboard::generalPasteboard();
        pb.clearContents();
        if pb.setString_forType(&NSString::from_str(text), &NSString::from_str(TYPE_STRING)) {
            Ok(())
        } else {
            anyhow::bail!("could not write to the pasteboard")
        }
    }

    // ── keycode of "v" in the current ASCII-capable layout ──

    #[link(name = "Carbon", kind = "framework")]
    extern "C" {
        fn TISCopyCurrentASCIICapableKeyboardLayoutInputSource() -> CFTypeRef;
        fn TISGetInputSourceProperty(source: CFTypeRef, key: *const c_void) -> CFTypeRef;
        static kTISPropertyUnicodeKeyLayoutData: *const c_void;
        fn LMGetKbdType() -> u8;
        fn UCKeyTranslate(
            layout: *const u8,
            virtual_key_code: u16,
            key_action: u16,
            modifier_key_state: u32,
            keyboard_type: u32,
            key_translate_options: u32,
            dead_key_state: *mut u32,
            max_string_length: usize,
            actual_string_length: *mut usize,
            unicode_string: *mut u16,
        ) -> i32;
    }

    /// ANSI keycodes used when the layout cannot be queried.
    fn default_keycode(ch: char) -> u16 {
        match ch {
            'c' => 8,
            _ => 9, // 'v'
        }
    }

    static KEYCODE_CACHE: Mutex<Option<std::collections::HashMap<char, (Instant, u16)>>> = Mutex::new(None);

    /// Virtual keycode that types `ch` (lowercase ASCII letter) in the current ASCII-capable layout,
    /// so Cmd+V / Cmd+C also work on Dvorak and friends.
    pub(crate) fn keycode_for_char(ch: char) -> u16 {
        if let Some(map) = KEYCODE_CACHE.lock().as_ref() {
            if let Some((at, code)) = map.get(&ch) {
                if at.elapsed() < Duration::from_secs(10) {
                    return *code;
                }
            }
        }
        // TIS must run on the main thread on recent macOS; never wait long for it.
        let found = if is_main_thread() {
            lookup_keycode(ch)
        } else {
            on_main_queue(Duration::from_millis(40), move || lookup_keycode(ch)).flatten()
        };
        let mut cache = KEYCODE_CACHE.lock();
        let map = cache.get_or_insert_with(Default::default);
        match found {
            Some(c) => {
                map.insert(ch, (Instant::now(), c));
                c
            }
            None => map.get(&ch).map(|(_, c)| *c).unwrap_or_else(|| default_keycode(ch)),
        }
    }

    fn lookup_keycode(ch: char) -> Option<u16> {
        unsafe {
            let source = TISCopyCurrentASCIICapableKeyboardLayoutInputSource();
            if source.is_null() {
                return None;
            }
            let result = (|| {
                let data_ref = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData);
                if data_ref.is_null() {
                    return None;
                }
                let data = CFData::wrap_under_get_rule(data_ref as _);
                let layout = data.bytes().as_ptr();
                let kbd = LMGetKbdType() as u32;
                let translate = |code: u16| -> Option<char> {
                    let mut dead: u32 = 0;
                    let mut len: usize = 0;
                    let mut buf = [0u16; 4];
                    // kUCKeyActionDown = 0, kUCKeyTranslateNoDeadKeysBit = 1
                    let status = UCKeyTranslate(layout, code, 0, 0, kbd, 1, &mut dead, buf.len(), &mut len, buf.as_mut_ptr());
                    if status != 0 || len == 0 {
                        return None;
                    }
                    String::from_utf16(&buf[..len]).ok()?.chars().next()
                };
                let preferred = default_keycode(ch);
                if translate(preferred) == Some(ch) {
                    return Some(preferred);
                }
                (0u16..128).find(|c| translate(*c) == Some(ch))
            })();
            CFRelease(source);
            result
        }
    }
}

#[cfg(all(test, target_os = "macos"))]
mod tests {
    use super::mac_impl::*;
    use objc2_app_kit::NSPasteboard;
    use objc2_foundation::NSString;

    /// Touches the real clipboard (and restores it): run with `--ignored`.
    #[test]
    #[ignore = "touches the real clipboard"]
    fn snapshot_write_restore_roundtrip() {
        let pb = NSPasteboard::generalPasteboard();
        let ty = NSString::from_str("public.utf8-plain-text");
        let original = "hoshiro-test-original";
        super::copy_to_clipboard(original).unwrap();
        let snap = snapshot_pasteboard(&pb);

        super::copy_to_clipboard("something else").unwrap();
        assert_eq!(pb.stringForType(&ty).unwrap().to_string(), "something else");

        restore_snapshot(&pb, &snap);
        assert_eq!(pb.stringForType(&ty).unwrap().to_string(), original);
    }

    #[test]
    fn keycode_lookup_has_sane_fallback() {
        let v = keycode_for_char('v');
        let c = keycode_for_char('c');
        assert!(v < 128 && c < 128 && v != c);
    }
}
